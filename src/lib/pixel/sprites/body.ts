/**
 * Bodies: one torso per outfit, one arm layer per pose frame.
 *
 * Every character is 16 wide and 26 tall. The head owns rows 0-13, with two
 * spare rows on top for horns and spiky hair; the body owns rows 14-25. Arms
 * are their own layer so a pose changes only what moves, and so every outfit
 * works in every pose without being drawn again.
 *
 * Slots:
 *   o outline     c/C outfit and its shade     t trim (collar, belt, hems)
 *   u undershirt  k/K accent (tie, sash)       g gold (buttons, braid)
 *   s/S skin      n hands (skin, or gloves)    p/P legs or skirt, and shade
 *   f shoes       j/J legwear under a skirt   U paper (a held scroll)
 */

