export type Pose = 'stand' | 'idle' | 'type' | 'raise' | 'slump' | 'cheer' | 'sleep' | 'think' | 'bow';

export interface PoseFrame {
    arms: ArmLayer;
    /** Rows the head drops by: a nod, a slump, sleep. */
    headDy: number;
    /** Rows the whole body moves by: negative is a hop. */
    bodyDy: number;
    eyes: 'open' | 'closed';
    /** Whether the character's own item is in hand. */
    holdsItem: boolean;
}

const f = (arms: ArmLayer, headDy = 0, eyes: 'open' | 'closed' = 'open', bodyDy = 0, holdsItem = false): PoseFrame => ({
    arms,
    headDy,
    bodyDy,
    eyes,
    holdsItem,
});

