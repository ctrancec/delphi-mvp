export type IconId = keyof typeof ICONS;

/** The icon as an SVG path of unit squares, for `fill="currentColor"`. */
export function iconPath(id: IconId): string {
    const g = ICONS[id];
    const parts: string[] = [];
    for (let y = 0; y < g.h; y++) {
        const row = g.rows[y];
        let x = 0;
        while (x < g.w) {
            if (row[x] !== '#') {
                x++;
                continue;
            }
            // Runs of pixels become one rectangle, so a 16-wide bar is one command.
            let end = x;
            while (end < g.w && row[end] === '#') end++;
            parts.push(`M${x} ${y}h${end - x}v1h-${end - x}z`);
            x = end;
        }
    }
    return parts.join('');
}
